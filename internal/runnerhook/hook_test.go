// needTools skips a test that runs the hook where bash, node or git is
// missing; the hook runs on Linux runner hosts only.
func needTools(t *testing.T) string {
	t.Helper()
	if runtime.GOOS != "linux" {
		t.Skip("the hook runs on Linux runner hosts")
	}
	for _, tool := range []string{"bash", "git"} {
		if _, err := exec.LookPath(tool); err != nil {
			t.Skip(tool + " is not installed")
		}
	}
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node is not installed")
	}
	return node
}

// Made-up workflow files shaped like the contract of Core's user execution
// set: nibfin-job.yml has one top-level IMAGE_REF line and three calls of
// nibfin-core's Action, nibfin-shared-runner.yml calls none. They are not
// copies of Core's templates.
const (
	sharedTemplate = "# Generated by gh nibfin\nname: Nibfin shared runner\non:\n  workflow_dispatch:\n    inputs:\n      assignee: {required: true}\njobs:\n  run:\n    uses: ./.github/workflows/nibfin-job.yml\n"
	jobTemplate    = "# Generated by gh nibfin\nname: Nibfin Job\non: workflow_call\nenv:\n  IMAGE_REF: @IMAGE@\njobs:\n  run:\n    steps:\n      - uses: taco3064/nibfin-core/action@@COMMIT@\n        with: {step: start}\n      - run: podman pull \"$IMAGE_REF\"\n      - uses: taco3064/nibfin-core/action@@COMMIT@\n        with: {step: finish}\n      - if: failure()\n        uses: taco3064/nibfin-core/action@@COMMIT@\n"
)

// rendered is the execution set as render-workflows prints it, keyed by
// repository path, for img and the Action commit c.
func rendered(img, c string) map[string][]byte {
	job := strings.NewReplacer("@IMAGE@", img, "@COMMIT@", c).Replace(jobTemplate)
	return map[string][]byte{
		".github/workflows/nibfin-issue.yml":          []byte("# Generated by gh nibfin\nname: issue\n"),
		".github/workflows/nibfin-shared-runner.yml":  []byte(sharedTemplate),
		".github/workflows/nibfin-job.yml":            []byte(job),
		".github/workflows/nibfin-runner-request.yml": []byte("# Generated by gh nibfin\nname: runner request\n"),
	}
}

// official returns the execution repository's two files for img, with the
// image's commit as their Action commit, as init and upgrade write them.
func official(t *testing.T, img string) map[string][]byte {
	t.Helper()
	return officialAt(img, commit)
}

// officialAt is official with the Action commit c.
func officialAt(img, c string) map[string][]byte {
	out := map[string][]byte{}
	for _, f := range runnerhook.Workflows {
		out[f] = rendered(img, c)[".github/workflows/"+f]
	}
	return out
}

