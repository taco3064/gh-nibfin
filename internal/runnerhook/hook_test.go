func TestHookRefusesChangedFiles(t *testing.T) {
	change := func(f *fixture, file string, fn func([]byte) []byte) {
		f.files = map[string][]byte{}
		for k, v := range official(f.t, image) {
			f.files[k] = v
		}
		f.files[file] = fn(bytes.Clone(f.files[file]))
	}
	t.Run("one byte in the shared runner", func(t *testing.T) {
		f := newFixture(t)
		change(f, "nibfin-shared-runner.yml", func(b []byte) []byte { b[len(b)/2] ^= 1; return b })
		out := f.refuses("nibfin-shared-runner.yml differs from the official template")
		if !strings.Contains(out, "gh nibfin upgrade") {
			t.Errorf("no next step: %s", out)
		}
	})
	t.Run("one byte in the job", func(t *testing.T) {
		f := newFixture(t)
		change(f, "nibfin-job.yml", func(b []byte) []byte { return bytes.Replace(b, []byte("podman pull"), []byte("podman pulL"), 1) })
		f.refuses("nibfin-job.yml differs from the official template")
	})
	t.Run("two image lines", func(t *testing.T) {
		f := newFixture(t)
		line := []byte("  IMAGE_REF: " + image + "\n")
		change(f, "nibfin-job.yml", func(b []byte) []byte { return bytes.Replace(b, line, append(bytes.Clone(line), line...), 1) })
		f.refuses("has 2 IMAGE_REF lines")
	})
	t.Run("another image", func(t *testing.T) {
		f := newFixture(t)
		change(f, "nibfin-job.yml", func(b []byte) []byte {
			return bytes.Replace(b, []byte(image), []byte("ghcr.io/evil/nibfin@sha256:"+digest), 1)
		})
		f.refuses("has 0 IMAGE_REF lines")
	})
	t.Run("a missing file", func(t *testing.T) {
		f := newFixture(t)
		delete(f.files, "nibfin-job.yml")
		f.refuses("is not readable without a credential (HTTP 404)")
	})
	t.Run("no file content is printed", func(t *testing.T) {
		f := newFixture(t)
		change(f, "nibfin-job.yml", func(b []byte) []byte { return append(b, []byte("SECRET-LOOKING-LINE\n")...) })
		out := f.refuses("differs")
		if strings.Contains(out, "SECRET-LOOKING-LINE") {
			t.Errorf("the refusal prints the file: %s", out)
		}
	})
}

func TestHookBindsTheActionCommit(t *testing.T) {
	const other = "ffffffffffffffffffffffffffffffffffffffff"
	t.Run("another bound commit", func(t *testing.T) {
		// Any commit is accepted once the image's attestation names it.
		f := newFixture(t)
		f.files = officialAt(image, other)
		f.attest = attestations(f.ca.bundle(t, digest, bundleOpts{sourceDigest: other}))
		f.accepts()
	})
	t.Run("a commit the image was not built from", func(t *testing.T) {
		f := newFixture(t)
		f.files = officialAt(image, other)
		out := f.refuses("the Action commit " + other + " is not the image's source commit \"" + commit + "\"")
		if !strings.Contains(out, "gh nibfin upgrade") {
			t.Errorf("no next step: %s", out)
		}
	})
	t.Run("no source commit in the certificate", func(t *testing.T) {
		f := newFixture(t)
		f.attest = attestations(f.ca.bundle(t, digest, bundleOpts{noSourceDigest: true}))
		f.refuses("is not the image's source commit \"\"")
	})
	t.Run("two commits", func(t *testing.T) {
		f := newFixture(t)
		f.files = official(t, image)
		f.files["nibfin-job.yml"] = bytes.Replace(f.files["nibfin-job.yml"], []byte("action@"+commit), []byte("action@"+other), 1)
		f.refuses("call taco3064/nibfin-core's Action at 2 commits, not one")
		if len(f.hits) != 2 {
			t.Errorf("the hook read %v; it refuses before reading the attestations", f.hits)
		}
	})
	t.Run("an Action call the official file lacks", func(t *testing.T) {
		f := newFixture(t)
		f.files = official(t, image)
		f.files["nibfin-shared-runner.yml"] = append(bytes.Clone(f.files["nibfin-shared-runner.yml"]), []byte("      - uses: taco3064/nibfin-core/action@"+commit+"\n")...)
		f.refuses("nibfin-shared-runner.yml differs from the official template")
	})
	t.Run("an Action of another repository", func(t *testing.T) {
		f := newFixture(t)
		f.files = official(t, image)
		f.files["nibfin-job.yml"] = bytes.Replace(f.files["nibfin-job.yml"], []byte("taco3064/nibfin-core/action@"), []byte("evil/nibfin-core/action@"), 1)
		f.refuses("nibfin-job.yml differs from the official template")
	})
	t.Run("an Action pinned to a tag", func(t *testing.T) {
		f := newFixture(t)
		f.files = official(t, image)
		f.files["nibfin-job.yml"] = bytes.Replace(f.files["nibfin-job.yml"], []byte("action@"+commit), []byte("action@main"), 1)
		f.refuses("nibfin-job.yml differs from the official template")
	})
	t.Run("no Action call", func(t *testing.T) {
		f := newFixture(t)
		f.files = official(t, image)
		f.files["nibfin-job.yml"] = bytes.ReplaceAll(f.files["nibfin-job.yml"], []byte("uses: taco3064/nibfin-core/action@"+commit), []byte("run: true"))
		f.refuses("nibfin-job.yml differs from the official template")
	})
}

