type issueDoc struct {
	On struct {
		WorkflowRun *struct {
			Workflows []string `yaml:"workflows"`
			Types     []string `yaml:"types"`
		} `yaml:"workflow_run"`
		Push struct {
			Branches []string `yaml:"branches"`
		} `yaml:"push"`
		Issues struct {
			Types []string `yaml:"types"`
		} `yaml:"issues"`
		PullRequestReview struct {
			Types []string `yaml:"types"`
		} `yaml:"pull_request_review"`
	} `yaml:"on"`
	Jobs map[string]struct {
		RunsOn string `yaml:"runs-on"`
		Steps  []struct {
			Env map[string]string `yaml:"env"`
			Run string            `yaml:"run"`
		} `yaml:"steps"`
	} `yaml:"jobs"`
}

func parseIssue(t *testing.T, p Params) (issueDoc, string) {
	t.Helper()
	b := render(t, Peer, p)[".github/workflows/nibfin-issue.yml"]
	var d issueDoc
	if err := yaml.Unmarshal(b, &d); err != nil {
		t.Fatalf("parse nibfin-issue.yml: %v\n%s", err, b)
	}
	return d, string(b)
}

func TestRenderIssueCaller(t *testing.T) {
	p := params()
	p.DefaultBranch = "trunk"
	p.Workflows = []string{"Image", "CI", "Image", `Lint "strict" #1: a, b`}
	d, text := parseIssue(t, p)
	if d.On.WorkflowRun == nil {
		t.Fatal("no workflow_run trigger")
	}
	if want := []string{"CI", "Image", `Lint "strict" #1: a, b`}; !slices.Equal(d.On.WorkflowRun.Workflows, want) {
		t.Errorf("workflows %q, want %q", d.On.WorkflowRun.Workflows, want)
	}
	if !strings.Contains(text, `    workflows: ["CI", "Image", "Lint \"strict\" #1: a, b"]`+"\n") {
		t.Errorf("workflows are not a quoted flow sequence:\n%s", text)
	}
	if !slices.Equal(d.On.WorkflowRun.Types, []string{"completed"}) {
		t.Errorf("workflow_run types %v", d.On.WorkflowRun.Types)
	}
	if !slices.Equal(d.On.Push.Branches, []string{"trunk"}) {
		t.Errorf("push branches %v, want [trunk]", d.On.Push.Branches)
	}
	if want := []string{"opened", "reopened", "closed", "assigned", "unassigned", "labeled", "unlabeled"}; !slices.Equal(d.On.Issues.Types, want) {
		t.Errorf("issues types %v", d.On.Issues.Types)
	}
	if !slices.Equal(d.On.PullRequestReview.Types, []string{"submitted"}) {
		t.Errorf("pull_request_review types %v, want [submitted]", d.On.PullRequestReview.Types)
	}
	wake, ok := d.Jobs["wake"]
	if !ok || len(d.Jobs) != 1 || wake.RunsOn != "ubuntu-24.04" || len(wake.Steps) != 1 {
		t.Fatalf("jobs %+v, want one wake job on ubuntu-24.04 with one step", d.Jobs)
	}
	step := wake.Steps[0]
	if step.Env["GH_TOKEN"] != "${{ secrets.NIBFIN_GITHUB_TOKEN }}" || step.Env["EXECUTION_REPO"] != "${{ vars.NIBFIN_EXECUTION_REPO }}" {
		t.Errorf("wake env %v", step.Env)
	}
	if step.Env["REVIEW_BRANCH"] != "${{ github.event.pull_request.head.ref }}" ||
		step.Env["REVIEW_HEAD_REPO"] != "${{ github.event.pull_request.head.repo.full_name }}" {
		t.Errorf("wake review env %v", step.Env)
	}
	if !strings.Contains(text, "|| github.event.pull_request.head.ref || github.event.check_suite.head_branch") {
		t.Error("run-name does not title a review run by its head branch")
	}
	for _, want := range []string{
		`gh workflow run nibfin-shared-runner.yml --repo "$EXECUTION_REPO" "${inputs[@]}"`,
		`if ! jq -e 'index("scope") != null or index("request") != null' <<<"$ISSUE_LABELS" >/dev/null; then`,
		`if [ "$PUSH_REF" != "refs/heads/$DEFAULT_BRANCH" ]; then`,
	} {
		if !strings.Contains(step.Run, want) {
			t.Errorf("the wake script has no %q", want)
		}
	}
	if strings.Contains(step.Run, "${{") {
		t.Error("the wake script interpolates an expression; event text must come through env")
	}
	if !strings.Contains(text, "\npermissions: {}\n") {
		t.Error("nibfin-issue.yml does not drop permissions")
	}
}

