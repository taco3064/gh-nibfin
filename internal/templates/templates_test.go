const testImage = "ghcr.io/taco3064/nibfin@sha256:47e9f06d0000000000000000000000000000000000000000000000000000abcd"

func render(t *testing.T, set Set, p Params) map[string][]byte {
	t.Helper()
	out, err := Render(set, p)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	return out
}

func params() Params {
	return Params{Image: testImage, DefaultBranch: "main", Workflows: []string{"CI", "Image"}}
}

func TestRenderFiles(t *testing.T) {
	cases := map[Set][]string{
		Execution: {".github/workflows/nibfin-issue.yml", ".github/workflows/nibfin-job.yml", ".github/workflows/nibfin-runner-request.yml", ".github/workflows/nibfin-shared-runner.yml"},
		Peer:      {".github/workflows/nibfin-issue.yml"},
	}
	// The Job and the request workflow lead; Core's own copies follow them.
	headers := map[string]string{
		".github/workflows/nibfin-issue.yml":          "# Generated by gh nibfin from taco3064/nibfin-core@30e890d",
		".github/workflows/nibfin-shared-runner.yml":  "# Generated by gh nibfin from taco3064/nibfin-core@30e890d",
		".github/workflows/nibfin-job.yml":            "# Generated by gh nibfin, with the image pinned by digest. Core's own",
		".github/workflows/nibfin-runner-request.yml": "# Generated by gh nibfin. Update it with `gh nibfin upgrade`.",
	}
	for set, want := range cases {
		if got := Files(set); !slices.Equal(slices.Sorted(slices.Values(got)), want) || got[0] != ".github/workflows/nibfin-issue.yml" {
			t.Errorf("set %d: Files %v, want %v starting with nibfin-issue.yml", set, got, want)
		}
		out := render(t, set, params())
		if got := slices.Sorted(maps.Keys(out)); !slices.Equal(got, want) {
			t.Errorf("set %d: files %v, want %v", set, got, want)
		}
		for name, b := range out {
			var doc map[string]any
			if err := yaml.Unmarshal(b, &doc); err != nil {
				t.Errorf("%s does not parse: %v", name, err)
			}
			for _, key := range []string{"name", "on", "permissions", "jobs"} {
				if _, ok := doc[key]; !ok {
					t.Errorf("%s has no %s:", name, key)
				}
			}
			if first, _, _ := strings.Cut(string(b), "\n"); first != headers[name] {
				t.Errorf("%s starts with %q, want %q", name, first, headers[name])
			}
			if strings.Contains(string(b), "[[") || strings.Contains(string(b), "]]") {
				t.Errorf("%s has an unrendered template action", name)
			}
		}
	}
	// The peer's caller is the execution set's caller.
	e, p := render(t, Execution, params()), render(t, Peer, params())
	if !bytes.Equal(e[".github/workflows/nibfin-issue.yml"], p[".github/workflows/nibfin-issue.yml"]) {
		t.Error("the execution and peer nibfin-issue.yml differ")
	}
}

var usesLine = regexp.MustCompile(`(?m)^\s*(?:-\s*)?uses:\s*(\S+)`)

func TestRenderSelfContained(t *testing.T) {
	var uses []string
	for name, b := range render(t, Execution, params()) {
		for _, m := range usesLine.FindAllStringSubmatch(string(b), -1) {
			if strings.Contains(strings.ToLower(m[1]), "taco3064/") {
				t.Errorf("%s uses %s", name, m[1])
			}
			uses = append(uses, m[1])
		}
	}
	slices.Sort(uses)
	if want := []string{"./.github/workflows/nibfin-job.yml", "actions/checkout@v7"}; !slices.Equal(uses, want) {
		t.Errorf("uses %v, want %v", uses, want)
	}
}

func TestRenderPinsImage(t *testing.T) {
	job := string(render(t, Execution, params())[".github/workflows/nibfin-job.yml"])
	if !strings.Contains(job, "\n  IMAGE_REF: "+testImage+"\n") {
		t.Errorf("IMAGE_REF is not the pinned image:\n%s", job)
	}
	if strings.Contains(job, ":main") || strings.Contains(job, "steps.image") {
		t.Error("the Job still refers to :main or the old image step output")
	}
	if n := strings.Count(job, testImage); n != 1 {
		t.Errorf("the image appears %d times, want once (in IMAGE_REF)", n)
	}
	pulls := regexp.MustCompile(`podman pull .*`).FindAllString(job, -1)
	if len(pulls) != 3 {
		t.Errorf("podman pull lines %q, want 3", pulls)
	}
	for _, l := range pulls {
		if l != `podman pull "$IMAGE_REF"` {
			t.Errorf("pull %q does not use IMAGE_REF", l)
		}
	}
	// Every podman run starts a container from "$IMAGE_REF".
	runs := regexp.MustCompile(`(?s)podman run .*?nibfin (?:route|run) `).FindAllString(job, -1)
	if len(runs) != 3 {
		t.Fatalf("podman run commands %d, want 3", len(runs))
	}
	for _, r := range runs {
		if !strings.Contains(r, `"$IMAGE_REF" nibfin `) {
			t.Errorf("podman run does not use IMAGE_REF: %s", r)
		}
	}
	if !strings.Contains(job, `id=$(podman image inspect --format '{{.Id}}' "$IMAGE_REF")`) {
		t.Error("the stage job does not keep the pinned image's ID")
	}
}

