func TestRenderDeterministic(t *testing.T) {
	a := render(t, Execution, params())
	p := params()
	p.Workflows = []string{"Image", "CI"}
	b := render(t, Execution, p)
	if !maps.EqualFunc(a, b, bytes.Equal) {
		t.Error("the same input renders different bytes")
	}
	for name, body := range a {
		if bytes.ContainsRune(body, '\r') {
			t.Errorf("%s has a carriage return; the templates must be checked out with LF endings", name)
		}
	}
}

func TestRenderRejects(t *testing.T) {
	bad := map[string]func(*Params){
		"tag image":       func(p *Params) { p.Image = "ghcr.io/taco3064/nibfin:main" },
		"other image":     func(p *Params) { p.Image = strings.Replace(testImage, "taco3064/nibfin", "evil/nibfin", 1) },
		"short digest":    func(p *Params) { p.Image = "ghcr.io/taco3064/nibfin@sha256:abc" },
		"upper digest":    func(p *Params) { p.Image = strings.ToUpper(testImage) },
		"image newline":   func(p *Params) { p.Image = testImage + "\n" },
		"empty branch":    func(p *Params) { p.DefaultBranch = "" },
		"branch newline":  func(p *Params) { p.DefaultBranch = "main\n  workflow_dispatch:" },
		"branch quote":    func(p *Params) { p.DefaultBranch = `ma"in` },
		"empty workflow":  func(p *Params) { p.Workflows = []string{"CI", " "} },
		"workflow inject": func(p *Params) { p.Workflows = []string{"CI\n  workflow_dispatch:"} },
	}
	for name, edit := range bad {
		p := params()
		edit(&p)
		_, err := Render(Execution, p)
		if code := op.Code(err); code != op.CodeInvalidTemplateInput {
			t.Errorf("%s: code %q (%v), want %s", name, code, err, op.CodeInvalidTemplateInput)
		}
	}
	if _, err := Render(Set(9), params()); op.Code(err) != op.CodeInvalidTemplateInput {
		t.Errorf("unknown set: %v", err)
	}
}

