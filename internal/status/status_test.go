func TestPendingComment(t *testing.T) {
	// The actor of the latest pending label event, across pages and out of
	// order; the oldest marked comment of that actor, across pages.
	page := []any{}
	for i := 0; i < 99; i++ {
		page = append(page, map[string]any{"event": "commented", "created_at": "2026-01-01T00:00:00Z"})
	}
	page = append(page, labeled(7, "pending", "2026-11-20T00:00:00Z"))
	cpage := []any{}
	for i := 0; i < 98; i++ {
		cpage = append(cpage, comment(int64(1000+i), 7, "no marker", "2026-11-01T00:00:00Z"))
	}
	cpage = append(cpage,
		comment(50, 9, marker+"fake", "2026-11-01T00:00:00Z"),
		comment(60, 7, marker+"newer", "2026-11-21T00:00:00Z"))
	routes := map[string]any{
		events1: page,
		events2: []any{
			labeled(9, "pending", "2026-11-25T00:00:00Z"),
			labeled(7, "pending", "2026-11-26T00:00:00Z"),
			labeled(9, "scope", "2026-11-27T00:00:00Z"),
			map[string]any{"event": "unlabeled", "created_at": "2026-11-28T00:00:00Z", "actor": map[string]any{"id": 9}, "label": map[string]any{"name": "pending"}},
		},
		comments1: cpage,
		comments2: []any{
			comment(61, 7, marker+"oldest", "2026-11-15T00:00:00Z"),
			comment(62, 7, " "+marker+"not at start", "2026-11-14T00:00:00Z"),
		},
	}
	is := pendingIssue(t, routes)
	if is.PendingComment != "https://github.com/o/r/issues/1#issuecomment-61" || is.PendingCommentError != nil {
		t.Errorf("issue = %+v", is)
	}

	// The latest label event was by someone else: only their comment counts.
	routes[events2] = []any{labeled(7, "pending", "2026-11-26T00:00:00Z"), labeled(9, "Pending", "2026-11-27T00:00:00Z")}
	if is := pendingIssue(t, routes); is.PendingComment != "https://github.com/o/r/issues/1#issuecomment-50" {
		t.Errorf("issue = %+v", is)
	}

	// No marked comment by the actor: no link, no error.
	routes[events2] = []any{labeled(8, "pending", "2026-11-27T00:00:00Z")}
	if is := pendingIssue(t, routes); is.PendingComment != "" || is.PendingCommentError != nil {
		t.Errorf("issue = %+v", is)
	}

	// No pending label event at all: comments are not read.
	routes = map[string]any{events1: []any{labeled(7, "scope", "2026-11-27T00:00:00Z")}, comments1: &api.HTTPError{StatusCode: 500}}
	if is := pendingIssue(t, routes); is.PendingComment != "" || is.PendingCommentError != nil {
		t.Errorf("issue = %+v", is)
	}

	// Read failures are the Issue's error.
	routes = map[string]any{events1: &api.HTTPError{StatusCode: 410, Message: "Gone"}}
	if is := pendingIssue(t, routes); is.PendingCommentError == nil || !strings.Contains(is.PendingCommentError.Error(), "HTTP 410: Gone") {
		t.Errorf("issue = %+v", is)
	}
	routes = map[string]any{events1: []any{labeled(7, "pending", "2026-11-27T00:00:00Z")}, comments1: &api.HTTPError{StatusCode: 500}}
	if is := pendingIssue(t, routes); is.PendingCommentError == nil || is.PendingCommentError.Code != op.CodeGitHubAPIFailed {
		t.Errorf("issue = %+v", is)
	}

	// An Issue without pending reads nothing.
	fx := setup(t, map[string]any{})
	r := &reader{c: fx.gh, host: "github.com"}
	r.withPending(context.Background(), "o/r", Issue{Number: 1})
	if len(fx.gh.gets) != 0 {
		t.Errorf("reads = %v", fx.gh.gets)
	}
}

