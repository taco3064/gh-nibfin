// fakeGH answers GET requests from a map of path (with query) to a JSON
// value; an error value is returned as the error. Any other method fails.
type fakeGH struct {
	t      *testing.T
	routes map[string]any
	gets   []string
}

func (f *fakeGH) DoWithContext(_ context.Context, method, p string, body io.Reader, out any) error {
	if method != http.MethodGet || body != nil {
		f.t.Errorf("status sent %s %s", method, p)
		return fmt.Errorf("write")
	}
	f.gets = append(f.gets, p)
	v, ok := f.routes[p]
	if !ok {
		return &api.HTTPError{StatusCode: http.StatusNotFound, Message: "Not Found"}
	}
	if err, ok := v.(error); ok {
		return err
	}
	b, err := json.Marshal(v)
	if err != nil {
		f.t.Fatal(err)
	}
	return json.Unmarshal(b, out)
}

func file(s string) map[string]string {
	return map[string]string{"encoding": "base64", "content": base64.StdEncoding.EncodeToString([]byte(s))}
}

