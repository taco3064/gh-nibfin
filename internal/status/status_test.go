func run(t *testing.T, repo string) op.Result {
	t.Helper()
	p, res, err := op.ReadBack(context.Background(), New(op.RepoParams{Repo: repo}))
	if err != nil {
		t.Fatalf("status: %v", err)
	}
	if !p.ReadOnly || p.Operation != "status" || len(p.Steps) != 0 {
		t.Errorf("plan = %+v", p)
	}
	return res
}

func q(path string, kv ...string) string {
	v := url.Values{}
	for i := 0; i < len(kv); i += 2 {
		v.Set(kv[i], kv[i+1])
	}
	return path + "?" + v.Encode()
}

func searchPath(page int) string {
	return q("search/issues", "q", "is:issue is:open label:scope assignee:@me", "per_page", "100", "page", fmt.Sprint(page))
}

func item(repo string, n int, labels ...string) map[string]any {
	ls := []map[string]string{}
	for _, l := range labels {
		ls = append(ls, map[string]string{"name": l})
	}
	return map[string]any{
		"number": n, "title": fmt.Sprintf("Issue %d", n),
		"html_url":       fmt.Sprintf("https://github.com/%s/issues/%d", repo, n),
		"repository_url": "https://api.github.com/repos/" + repo,
		"labels":         ls,
		"created_at":     fmt.Sprintf("2026-11-%02dT00:00:00Z", 1+n%20),
	}
}

func jobYML(ref string) string {
	return "# Generated by gh nibfin from x\nname: Nibfin · Job\nenv:\n  IMAGE_REF: " + ref + "\njobs: {}\n"
}

func TestPersonView(t *testing.T) {
	page1 := []any{}
	for i := 1; i <= 100; i++ {
		page1 = append(page1, item("b/two", i))
	}
	routes := map[string]any{
		"user":        map[string]any{"login": "me", "id": 1},
		searchPath(1): map[string]any{"total_count": 102, "items": page1},
		searchPath(2): map[string]any{"total_count": 102, "items": []any{item("a/one", 5, "scope", "Pause"), item("a/one", 3, "scope")}},
		"repos/a/one/contents/.github/workflows/nibfin-job.yml": file(jobYML(imgA)),
		"repos/b/two/contents/.github/workflows/nibfin-job.yml": file(jobYML(imgB)),
	}
	fx := setup(t, routes)
	res := run(t, "")
	if res["user"] != "me" || res["githubHost"] != "github.com" || res["truncated"] != false || res["issuesError"] != nil {
		t.Errorf("result = %v", res)
	}
	if _, ok := res["host"].(op.HostReport); !ok {
		t.Errorf("host = %#v", res["host"])
	}
	if res["latestImage"] != (LatestImage{Ref: imgA}) {
		t.Errorf("latest = %v", res["latestImage"])
	}
	repos := res["repos"].([]RepoIssues)
	if len(repos) != 2 || repos[0].Repo != "a/one" || repos[1].Repo != "b/two" || len(repos[1].Issues) != 100 {
		t.Fatalf("repos = %+v", repos)
	}
	one := repos[0]
	if one.Issues[0].Number != 3 || one.Issues[1].Number != 5 || !one.Issues[1].Pause || one.Issues[0].Pause {
		t.Errorf("issues = %+v", one.Issues)
	}
	if !reflect.DeepEqual(one.Issues[1].Labels, []string{"scope", "Pause"}) {
		t.Errorf("labels = %v", one.Issues[1].Labels)
	}
	if one.Image.Set != "execution" || *one.Image.Ref != imgA || !*one.Image.Latest {
		t.Errorf("image a = %+v", one.Image)
	}
	if two := repos[1].Image; *two.Ref != imgB || *two.Latest {
		t.Errorf("image b = %+v", two)
	}
	if !reflect.DeepEqual(fx.hosts, []string{"github.com"}) {
		t.Errorf("hosts = %v", fx.hosts)
	}
	for _, g := range fx.gh.gets {
		if g == searchPath(3) {
			t.Error("searched past a short page")
		}
	}
}

