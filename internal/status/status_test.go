func TestNibfinRunCases(t *testing.T) {
	runs := q("repos/o/r/actions/runs", "status", "success", "created", ">=2026-11-09T00:00:00+00:00", "per_page", "100", "page", "1")

	// No merged PR: the commit's date, and no run after it.
	routes := repoRoutes()
	routes["repos/o/r/commits/c2/pulls"] = []any{}
	routes[runs] = map[string]any{"workflow_runs": []any{map[string]any{"name": "CI", "created_at": "2026-11-11T00:00:00Z"}}}
	setup(t, routes)
	got := run(t, "github.com/o/r")["nibfinRun"].(NibfinRun)
	if want := (NibfinRun{Initialized: true, InitCommit: "c2", MergedAt: "2026-11-09T00:00:00Z"}); !reflect.DeepEqual(got, want) {
		t.Errorf("run = %+v", got)
	}

	// No generated file in the history.
	routes = repoRoutes()
	routes["repos/o/r/contents/.github/workflows/nibfin-issue.yml?ref=c2"] = file("name: x\n")
	routes["repos/o/r/contents/.github/workflows/nibfin-issue.yml?ref=c3"] = file("name: y\n")
	setup(t, routes)
	if got := run(t, "github.com/o/r")["nibfinRun"].(NibfinRun); !reflect.DeepEqual(got, NibfinRun{}) {
		t.Errorf("run = %+v", got)
	}

	// A failed read is the part's error.
	routes = repoRoutes()
	routes["repos/o/r/commits/c2/pulls"] = &api.HTTPError{StatusCode: 500, Message: "boom"}
	routes["repos/o/r/issues?state=open&per_page=100&page=1"] = &api.HTTPError{StatusCode: 404, Message: "Not Found"}
	setup(t, routes)
	res := run(t, "github.com/o/r")
	if got := res["nibfinRun"].(NibfinRun); got.Error == nil || got.Error.Code != op.CodeGitHubAPIFailed || !strings.Contains(got.Error.Error(), "HTTP 500: boom") {
		t.Errorf("run = %+v", got)
	}
	if e := res["issuesError"].(*op.Error); e.Code != op.CodeGitHubAPIFailed || len(res["issues"].([]Issue)) != 0 {
		t.Errorf("issues = %v %v", e, res["issues"])
	}
}

