	events2   = "repos/o/r/issues/1/events?per_page=100&page=2"
	comments1 = "repos/o/r/issues/1/comments?per_page=100&page=1"
	comments2 = "repos/o/r/issues/1/comments?per_page=100&page=2"
	marker    = "<!-- nibfin:pending -->\n"
