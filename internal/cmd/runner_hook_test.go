package cmd

import (
	"context"
	"errors"
	"os/exec"
	"testing"

	"github.com/taco3064/gh-nibfin/internal/op"
	"github.com/taco3064/gh-nibfin/internal/runnerhook"
	"github.com/taco3064/gh-nibfin/internal/templates"
)

func TestRunnerHookFiles(t *testing.T) {
	oldImage, oldRender, oldFiles := hookImage, hookRender, hookFiles
	t.Cleanup(func() { hookImage, hookRender, hookFiles = oldImage, oldRender, oldFiles })
	const ref = "ghcr.io/taco3064/nibfin@sha256:" + "ab12ab12ab12ab12ab12ab12ab12ab12ab12ab12ab12ab12ab12ab12ab12ab12"
	hookImage = func(context.Context) (string, error) { return ref, nil }
	podman := func(ctx context.Context, args ...string) *exec.Cmd { return exec.CommandContext(ctx, "true") }
	rendered := map[string][]byte{".github/workflows/nibfin-job.yml": []byte("# Generated by gh nibfin\n")}
	var got templates.Params
	var gotSet templates.Set
	hookRender = func(_ context.Context, p templates.Podman, set templates.Set, params templates.Params) (map[string][]byte, error) {
		if p == nil {
			t.Error("no podman passed to the render")
		}
		gotSet, got = set, params
		return rendered, nil
	}
	var passed map[string][]byte
	hookFiles = func(_ context.Context, r map[string][]byte) (map[string][]byte, error) {
		passed = r
		return map[string][]byte{"ok": nil}, nil
	}
	out, err := runnerHookFiles(context.Background(), podman)
	if err != nil || out == nil {
		t.Fatalf("runnerHookFiles: %v", err)
	}
	if gotSet != templates.Execution || got.Run != ref || got.Image != runnerhook.PlaceholderImage || got.Commit != runnerhook.PlaceholderCommit || got.DefaultBranch == "" {
		t.Errorf("rendered set %v with %+v", gotSet, got)
	}
	if passed == nil || string(passed[".github/workflows/nibfin-job.yml"]) != "# Generated by gh nibfin\n" {
		t.Errorf("runnerhook.Files got %v", passed)
	}

	// An image or render failure keeps its code.
	hookImage = func(context.Context) (string, error) { return "", op.Errorf(op.CodeImageUnverified, "no attestation") }
	if _, err := runnerHookFiles(context.Background(), podman); op.Code(err) != op.CodeImageUnverified {
		t.Errorf("image failure: %v", err)
	}
	hookImage = func(context.Context) (string, error) { return ref, nil }
	hookRender = func(context.Context, templates.Podman, templates.Set, templates.Params) (map[string][]byte, error) {
		return nil, op.Wrap(op.CodePodmanFailed, errors.New("pull refused"))
	}
	if _, err := runnerHookFiles(context.Background(), podman); op.Code(err) != op.CodePodmanFailed {
		t.Errorf("render failure: %v", err)
	}
}
